"""Configuration and native Antigravity agent definitions for Codex profiles."""

from __future__ import annotations

import argparse
import json
import logging
import os
import re
import shlex
import sys
import tempfile
from pathlib import Path
from typing import Any

PLUGIN_DIR = Path(__file__).resolve().parent.parent
EXECUTOR = PLUGIN_DIR / "bin" / "codex_sdk_executor.py"
CONFIG_PATH = Path(os.environ.get("AGY_CODEX_CONFIG_PATH", PLUGIN_DIR / "config.json"))
PROFILE_DIR = Path(os.environ.get("AGY_CODEX_PROFILE_DIR", PLUGIN_DIR / "profiles"))
WORKSPACE_ROOT = Path(os.environ.get("AGY_CODEX_WORKSPACE_ROOT", PLUGIN_DIR.parent.parent))
GLOBAL_CONFIG = Path(os.environ.get("AGY_CODEX_GLOBAL_CONFIG", Path.home() / ".gemini/config"))
GLOBAL_AGENTS = Path(os.environ.get("AGY_CODEX_GLOBAL_AGENTS", GLOBAL_CONFIG / "agents"))
EXECUTION_MODES = ("preInvocation", "sdkExecutor")
EFFORTS = ("low", "medium", "high", "xhigh", "ultra")
SANDBOX_MODES = ("read-only", "workspace-write", "danger-full-access")
APPROVAL_POLICIES = ("never", "on-request", "untrusted")
MARKDOWN_MARKER = "<!-- Generated by codex-subagent -->"
NAME_PATTERN = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*")
RESERVED_NAMES = {"codex", "self", "research", "image-generator"}


def read_object(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def atomic_write(path: Path, contents: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as out:
        temporary = Path(out.name)
        try:
            out.write(contents)
            out.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def write_object(path: Path, data: dict[str, Any]) -> None:
    atomic_write(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def load_config() -> dict[str, Any]:
    defaults = read_object(PLUGIN_DIR / "config.example.json")
    if CONFIG_PATH.is_file():
        defaults.update(read_object(CONFIG_PATH))
    return validate_settings(defaults)


def validate_settings(settings: dict[str, Any]) -> dict[str, Any]:
    for field, options in (
        ("executionMode", EXECUTION_MODES), ("effort", EFFORTS),
        ("sandboxMode", SANDBOX_MODES), ("approvalPolicy", APPROVAL_POLICIES),
    ):
        if settings.get(field) not in options:
            raise ValueError(f"{field} must be one of {', '.join(options)}")
    for field in ("model", "description", "systemPrompt"):
        value = settings.get(field, "")
        if not isinstance(value, str) or (field == "model" and not value.strip()):
            raise ValueError(f"{field} must be a valid string")
    return settings


def validate_name(name: Any) -> str:
    if not isinstance(name, str) or len(name) > 64 or not NAME_PATTERN.fullmatch(name):
        raise ValueError("Use a lowercase profile name with letters, digits, and single hyphens")
    if name in RESERVED_NAMES:
        raise ValueError(f"Profile name {name!r} is reserved")
    return name


def normalize_profile(data: dict[str, Any], previous: dict[str, Any] | None = None) -> dict[str, Any]:
    name = validate_name(data.get("name"))
    defaults = {"description": f"Codex subagent profile {name}", "systemPrompt": "", **load_config()}
    for field in defaults:
        if previous and field in previous:
            defaults[field] = previous[field]
        if field in data:
            defaults[field] = data[field]
    return {"name": name, **validate_settings(defaults)}


def load_profiles() -> dict[str, dict[str, Any]]:
    profiles = {}
    for path in sorted(PROFILE_DIR.glob("*.json")):
        try:
            profile = normalize_profile(read_object(path))
            if path.stem != profile["name"]:
                raise ValueError("Profile name must match the filename")
        except (OSError, ValueError) as e:
            logging.getLogger(__name__).warning("Skipping profile %s: %s", path, e)
            continue
        profiles[profile["name"]] = profile
    return profiles


def sdk_definition(path: Path, name: str) -> bool:
    try:
        spec = read_object(path)
        return (
            spec.get("name") == name and not spec.get("disabled") and spec.get("subagent", True)
            and isinstance(spec.get("commandSpec"), dict)
        )
    except (OSError, ValueError):
        return False


def active_sdk_definition(name: str, cwd: str | None = None) -> bool:
    workspace = Path(cwd or os.getcwd()).resolve()
    dirs = [parent / ".agents" / "agents" for parent in (workspace, *workspace.parents)]
    dirs.extend((WORKSPACE_ROOT / ".agents/agents", GLOBAL_AGENTS))
    for directory in dirs:
        if sdk_definition(directory / f"{name}.json", name):
            return True
        if (directory / f"{name}.md").is_file():
            return False
    return False


def live_sdk_instance(session: dict[str, Any]) -> bool:
    if not session.get("sdkInstanceId"):
        return False
    if pid := session.get("sdkPid"):
        try:
            os.kill(pid, 0)
        except ProcessLookupError:
            return False
        except PermissionError:
            pass
    return True


def agent_files(name: str) -> list[Path]:
    return [
        folder / f"{name}.{suffix}"
        for folder in dict.fromkeys((WORKSPACE_ROOT / ".agents/agents", GLOBAL_AGENTS))
        for suffix in ("md", "json")
    ]


def plugin_owns(path: Path, name: str) -> bool:
    if path.suffix == ".json":
        try:
            doc = read_object(path)
            args = doc["commandSpec"]["args"]
            return doc["name"] == name and args[-3:] == [str(EXECUTOR), "--agent-name", name]
        except (OSError, ValueError, KeyError, TypeError, IndexError):
            return False
    try:
        if name == "codex" and path.is_symlink():
            # The original checkout installed this fallback as an absolute symlink.
            target = Path(os.readlink(path))
            if target.parts[-4:] == ("plugins", "codex-subagent", "agents", "codex.md"):
                return True
        contents = path.read_text(encoding="utf-8")
        return MARKDOWN_MARKER in contents or (
            name == "codex" and contents == (PLUGIN_DIR / "agents/codex.md").read_text(encoding="utf-8")
        )
    except OSError:
        return False


def apply_files(changes: dict[Path, str | None]) -> None:
    """Restore previously written files if any later write or removal fails."""
    originals = {}
    for path in changes:
        if path.is_symlink():
            originals[path] = (True, os.readlink(path))
        else:
            originals[path] = (False, path.read_text(encoding="utf-8") if path.exists() else None)
    changed = []
    try:
        for path, contents in changes.items():
            if contents is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write(path, contents)
            changed.append(path)
    except OSError:
        for path in reversed(changed):
            is_link, original = originals[path]
            if original is None:
                path.unlink(missing_ok=True)
            elif is_link:
                path.unlink(missing_ok=True)
                path.symlink_to(original)
            else:
                atomic_write(path, original)
        raise


def definition_changes(name: str, profile: dict[str, Any] | None) -> dict[Path, str | None]:
    changes = {}
    if profile is not None:
        description = profile.get("description") or f"OpenAI Codex subagent ({name})"
        is_sdk = profile["executionMode"] == "sdkExecutor"
        if is_sdk:
            definition = json.dumps({
                "name": name, "description": description, "subagent": True, "mainAgent": False,
                "disableModelSelection": True,
                "commandSpec": {"command": sys.executable, "args": ["-u", str(EXECUTOR), "--agent-name", name]},
            }, ensure_ascii=False, indent=2) + "\n"
        else:
            # JSON-quoted strings are valid YAML scalars, including colons, quotes, and newlines.
            definition = (
                f"---\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
                "subagent: true\nmainAgent: false\nmodel: flash_lite\ntools:\n  - send_message\n---\n\n"
                f"{MARKDOWN_MARKER}\n"
                "Your turns are routed to Codex by the PreInvocation hook.\n"
            )
    for path in agent_files(name):
        exists = path.exists() or path.is_symlink()
        owned = exists and plugin_owns(path, name)
        if profile is None:
            if owned:
                changes[path] = None
        else:
            if exists and not owned:
                raise ValueError(f"Conflicting agent definition exists at {path}")
            suffix = ".json" if is_sdk else ".md"
            if path.suffix == suffix:
                changes[path] = definition
            elif owned:
                changes[path] = None
    return changes


def install(mode: str) -> None:
    config = load_config()
    config["executionMode"] = mode
    changes = definition_changes("codex", config)
    changes[CONFIG_PATH] = json.dumps(config, indent=2) + "\n"
    hooks = read_object(PLUGIN_DIR / "hooks.json")
    hooks["codex-subagent-interceptor"]["PreInvocation"][0]["command"] = shlex.join(
        [sys.executable, str(PLUGIN_DIR / "bin/codex_hook_intercept.py")]
    )
    mcp = read_object(PLUGIN_DIR / "mcp_config.json")
    mcp["mcpServers"]["codex-subagent-control"].update({
        "command": sys.executable,
        "args": ["-u", str(PLUGIN_DIR / "bin/codex_mcp_server.py")],
    })
    for path, config_data in ((PLUGIN_DIR / "hooks.json", hooks), (PLUGIN_DIR / "mcp_config.json", mcp)):
        changes[path] = json.dumps(config_data, indent=2) + "\n"
    apply_files(changes)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--install-mode", required=True, choices=EXECUTION_MODES)
    install(parser.parse_args().install_mode)
